/**
 * 一次性：把 Cloudflare D1(SQLite) 的資料匯出成 PostgreSQL 可直接灌入的 SQL。
 * 這是 scripts/migrate-pg-to-d1.mjs 的反向操作（Cloudflare → 自架 NAS 回遷用）。
 *
 * 用法（在 repo 根目錄）：
 *   node scripts/migrate-d1-to-pg.mjs > pg-import.sql
 *   # 檢查一下內容，再灌進 Postgres：
 *   docker compose exec -T db psql -U "$POSTGRES_USER" -d "$POSTGRES_DB" -f - < pg-import.sql
 *
 * 前置：`npx wrangler login` 過、cf/wrangler.jsonc 裡的 D1 設定正確。
 * 本腳本只「讀」D1（SELECT），把 SQL 印到 stdout，不寫入任何資料庫。
 *
 * 轉換（對應 forward 腳本的反向）：
 *   - ISO 字串 → Postgres timestamp（直接吃 ISO 8601）
 *   - Delegation.active 0/1 → boolean false/true
 *   - 保留主鍵 id，最後用 setval 校正 sequence，避免新 id 撞號
 *   - 依外鍵相依順序插入：UserBinding 先，其餘在後
 */

import { execSync } from 'node:child_process';

const D1_NAME = process.env.D1_NAME || 'ehr-104';
const CF_DIR = 'cf';
const PAGE = 400; // 每次 SELECT 的列數，避免單次輸出過大

/** 欄位型別：ts=時間戳、bool=布林、其餘照原樣。 */
const TABLES = [
  {
    name: 'UserBinding',
    cols: ['id', 'lineUserId', 'companyId', 'internalCompanyId', 'empId', 'encryptedToken', 'iv', 'cookies', 'createdAt', 'updatedAt'],
    ts: ['createdAt', 'updatedAt'],
    bool: [],
  },
  {
    name: 'ScheduledTask',
    cols: ['id', 'userId', 'scheduledAt', 'lat', 'lng', 'status', 'result', 'createdAt', 'updatedAt'],
    ts: ['scheduledAt', 'createdAt', 'updatedAt'],
    bool: [],
  },
  {
    name: 'UsageLog',
    cols: ['id', 'userId', 'actorUserId', 'action', 'count', 'details', 'createdAt'],
    ts: ['createdAt'],
    bool: [],
  },
  {
    name: 'Delegation',
    cols: ['id', 'granterId', 'granteeId', 'active', 'expiresAt', 'createdAt', 'updatedAt'],
    ts: ['expiresAt', 'createdAt', 'updatedAt'],
    bool: ['active'],
  },
];

/**
 * 走 `npx wrangler`（execSync 預設經過 shell）而不是直接 spawn wrangler.js：
 *   - Node 22 在 Windows 上不允許 execFileSync 執行 .cmd（EINVAL）
 *   - 直接 spawn wrangler.js 的話 Cloudflare API 會回 7403 未授權
 *
 * 必須用 --command 而非 --file：--file 模式只回「執行了幾筆、讀了幾列」的統計摘要，
 * 不會回傳實際資料列。以下的 SQL 都不含引號，用雙引號包起來對 cmd.exe / sh 都安全。
 */
function d1Query(sql) {
  const out = execSync(`npx wrangler d1 execute ${D1_NAME} --remote --json --command "${sql}"`, {
    cwd: CF_DIR,
    encoding: 'utf8',
    maxBuffer: 64 * 1024 * 1024,
    stdio: ['ignore', 'pipe', 'pipe'],
  });
  // wrangler 會在 JSON 前後混進進度訊息，找出獨立成行的 '[' 當起點。
  const lines = out.split(/\r?\n/);
  const start = lines.findIndex((l) => l.trim() === '[');
  if (start === -1) throw new Error(`wrangler 沒有回傳 JSON:\n${out.slice(0, 500)}`);
  const parsed = JSON.parse(lines.slice(start).join('\n'));
  return parsed[0]?.results ?? [];
}

/** 把 JS 值轉成 Postgres SQL literal。 */
function lit(v, { isTs = false, isBool = false } = {}) {
  if (v === null || v === undefined) return 'NULL';
  if (isBool) return v ? 'true' : 'false';
  // 一定要用 ::timestamp 而非 ::timestamptz。
  // Prisma 的 DateTime 在 Postgres 是 TIMESTAMP(3) without time zone，存的是 UTC 值。
  // 轉成 timestamptz 再存進 naive 欄位，Postgres 會依「連線的 session TimeZone」換算，
  // 台北連線就會整批偏移 8 小時；轉成 timestamp 則直接忽略尾端的 Z，存字面 UTC，正確。
  if (isTs) return `'${String(v)}'::timestamp`;
  if (typeof v === 'number') return Number.isFinite(v) ? String(v) : 'NULL';
  return `'${String(v).replace(/'/g, "''")}'`;
}

const out = [];
out.push('-- Generated by scripts/migrate-d1-to-pg.mjs (D1 → PostgreSQL)');
out.push('BEGIN;');

let totalRows = 0;
const imported = [];

for (const t of TABLES) {
  let offset = 0;
  let n = 0;
  for (;;) {
    const rows = d1Query(`SELECT * FROM ${t.name} ORDER BY id LIMIT ${PAGE} OFFSET ${offset}`);
    if (rows.length === 0) break;
    for (const r of rows) {
      const vals = t.cols
        .map((c) => lit(r[c], { isTs: t.ts.includes(c), isBool: t.bool.includes(c) }))
        .join(', ');
      const quoted = t.cols.map((c) => `"${c}"`).join(', ');
      // ON CONFLICT DO NOTHING：讓腳本可重跑，不會因為重複灌入而整批失敗。
      out.push(`INSERT INTO "${t.name}" (${quoted}) VALUES (${vals}) ON CONFLICT ("id") DO NOTHING;`);
    }
    n += rows.length;
    offset += PAGE;
    if (rows.length < PAGE) break;
  }
  console.error(`  ${t.name}: ${n} rows`);
  totalRows += n;
  if (n > 0) imported.push(t.name);
}

out.push('-- 校正 sequence，避免之後新增的 id 與既有 id 相撞');
for (const name of imported) {
  out.push(
    `SELECT setval(pg_get_serial_sequence('"${name}"', 'id'), COALESCE((SELECT MAX("id") FROM "${name}"), 1), true);`,
  );
}
out.push('COMMIT;');

process.stdout.write(out.join('\n') + '\n');
console.error(`\nDone. ${totalRows} rows total。檢查後灌入 Postgres。`);
